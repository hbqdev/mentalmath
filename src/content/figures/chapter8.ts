/** The five-digit-square diagram: fan-out to the two factors, fan-in to a small addition column. */
const bigSquare = (
  base: string,
  d: string,
  up: string,
  down: string,
  caption: string | undefined,
  product: string,
  productNote: string,
  square: string,
  squareNote: string,
  total: string,
): FigureSpec =>
  row([
    split(base, d, up, down, ''),
    col(
      [
        { value: product, note: productNote },
        { op: '+', value: square, rule: true, note: squareNote },
        { value: total },
      ],
      caption,
    ),
  ])

