const money = (amounts: string[], total: string): FigureSpec => ({
  kind: 'column',
  lines: [
    ...amounts.map((v, i) => ({ value: v, rule: i === amounts.length - 1 })),
    { value: total },
  ],
})
const divide = (lines: FigureSpec[], average: string): FigureSpec =>
  row([
    stack([text(['Divide:'], 'left'), ...lines]),
    stack([text(['Average:'], 'left'), text([average])]),
  ])

